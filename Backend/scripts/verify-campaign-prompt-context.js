import assert from 'node:assert/strict';
import {campaignCallContext,buildDynamicPromptValues,campaignContextInstruction,renderDynamicPrompt} from '../src/voice/dynamic-prompt-values.js';
import {buildContextualOpeningInstruction} from '../src/voice/conversation-opening.js';
import {contactsFromCsv} from '../src/campaigns/csv.js';
const context={call_purpose:'appointment_reminder',summary:'Appointment tomorrow at 3 PM'};
const call={direction:'outbound',tenantId:'tenant-a',providerMetadata:{taskId:'task-a',context}};
const values=buildDynamicPromptValues({call,summaries:[{summary_text:'Old enquiry'}],followUp:{current_attempt:true,purpose:'old callback'}});
assert.equal(values['call.purpose'],context.call_purpose);
assert.equal(values['call.summary'],context.summary);
assert.ok(buildContextualOpeningInstruction(values,'Tamil').includes(context.summary));
assert.ok(campaignContextInstruction(values).includes('untrusted'));
assert.ok(renderDynamicPrompt('{{call.summary}}',values).text.includes(context.summary));
assert.equal(campaignCallContext({...call,direction:'inbound'}).summary,'');
assert.equal(campaignCallContext({direction:'outbound',providerMetadata:{context}}).summary,'');
assert.equal(buildDynamicPromptValues({call:{}})['call.purpose'],'unknown');
assert.equal(campaignCallContext({...call,providerMetadata:{taskId:'x',context:{summary:{unsafe:true}}}}).summary,'');
assert.equal(campaignCallContext({...call,providerMetadata:{taskId:'x',context:{summary:'a'.repeat(7000)}}}).summary.length,6000);
const batch=contactsFromCsv('phone,name,call_purpose,summary\n+919999999999,Test,appointment_reminder,Appointment tomorrow');
assert.equal(batch.contacts[0].context.call_purpose,'appointment_reminder');
assert.equal(batch.contacts[0].context.summary,'Appointment tomorrow');
assert.equal(campaignCallContext({...call,providerMetadata:{taskId:'other',context:{summary:'other tenant'}}}).summary,'other tenant');
assert.equal(values['call.summary'],context.summary);
console.log('Campaign context: purpose, summary, opening, placeholders, batch parsing, bounds and per-call separation passed');
